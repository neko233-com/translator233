//go:build ignore

// Generator for internal/onnx/api_offsets.go.
// Usage: go run tools/genortapi/main.go <onnxruntime_c_api.h> <out.go>
package main

import (
	"fmt"
	"os"
	"regexp"
	"strings"
)

var (
	reStatus  = regexp.MustCompile(`^ORT_API2_STATUS\s*\(\s*(\w+)`)
	reAPIT    = regexp.MustCompile(`^ORT_API_T\s*\([^,]*,\s*(\w+)`)
	reRelease = regexp.MustCompile(`^ORT_CLASS_RELEASE\s*\(\s*(\w+)\s*\)`)
	rePtr     = regexp.MustCompile(`\(\s*ORT_API_CALL\s*\*\s*(\w+)\s*\)`)
)

func main() {
	if len(os.Args) != 3 {
		fmt.Println("usage: genortapi <header> <out>")
		os.Exit(1)
	}
	src, err := os.ReadFile(os.Args[1])
	if err != nil {
		panic(err)
	}
	body, err := structBody(string(src), "struct OrtApi {")
	if err != nil {
		panic(err)
	}
	var names []string
	for _, stmt := range statements(body) {
		name := memberName(stmt)
		if name == "" {
			fmt.Fprintf(os.Stderr, "skip: %q\n", strings.TrimSpace(stmt))
			continue
		}
		names = append(names, name)
	}
	var b strings.Builder
	b.WriteString("// Code generated by tools/genortapi. DO NOT EDIT.\n\npackage ort\n\n")
	b.WriteString("// apiIndex maps OrtApi struct member names to their zero-based slot.\n")
	b.WriteString("var apiIndex = map[string]int{\n")
	for i, n := range names {
		fmt.Fprintf(&b, "\t%q: %d,\n", n, i)
	}
	b.WriteString("}\n")
	if err := os.WriteFile(os.Args[2], []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("wrote %d members to %s\n", len(names), os.Args[2])
}

func structBody(src, header string) (string, error) {
	i := strings.Index(src, header)
	if i < 0 {
		return "", fmt.Errorf("header %q not found", header)
	}
	i += len(header)
	depth := 1
	for j := i; j < len(src); j++ {
		switch src[j] {
		case '{':
			depth++
		case '}':
			depth--
			if depth == 0 {
				return src[i:j], nil
			}
		}
	}
	return "", fmt.Errorf("unterminated struct")
}

// statements splits a C struct body into top-level declarations, skipping
// comments and preprocessor lines.
func statements(body string) []string {
	var out []string
	var cur strings.Builder
	depth := 0
	for i := 0; i < len(body); i++ {
		c := body[i]
		switch {
		case c == '/' && i+1 < len(body) && body[i+1] == '/':
			for i < len(body) && body[i] != '\n' {
				i++
			}
			continue
		case c == '/' && i+1 < len(body) && body[i+1] == '*':
			if k := strings.Index(body[i+2:], "*/"); k >= 0 {
				i += k + 3
			} else {
				i = len(body)
			}
			continue
		case c == '#' && cur.Len() == 0:
			for i < len(body) && body[i] != '\n' {
				i++
			}
			continue
		}
		cur.WriteByte(c)
		switch c {
		case '(':
			depth++
		case ')':
			depth--
		case ';':
			if depth == 0 {
				out = append(out, cur.String())
				cur.Reset()
			}
		}
	}
	return out
}

func memberName(stmt string) string {
	s := strings.TrimSpace(stmt)
	if m := reStatus.FindStringSubmatch(s); m != nil {
		return m[1]
	}
	if m := reAPIT.FindStringSubmatch(s); m != nil {
		return m[1]
	}
	if m := reRelease.FindStringSubmatch(s); m != nil {
		return "Release" + m[1]
	}
	if m := rePtr.FindStringSubmatch(s); m != nil {
		return m[1]
	}
	return ""
}
